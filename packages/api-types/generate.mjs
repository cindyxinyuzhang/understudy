/**
 * Regenerate the TypeScript view of the API.
 *
 *   FastAPI route signatures  ->  openapi.json  ->  schema.d.ts  ->  frontend
 *
 * Both artefacts are committed. CI reruns this and fails on a diff, which is what
 * actually enforces the contract: you cannot change a response model in Python without
 * either updating the generated types in the same commit or breaking the build. Types
 * that were generated once and then drifted are worse than no generated types at all,
 * because they look authoritative.
 */
import { execFileSync } from "node:child_process";
import { existsSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import openapiTS, { astToString } from "openapi-typescript";

const here = dirname(fileURLToPath(import.meta.url));
const apiDir = resolve(here, "../../apps/api");
const schemaJson = join(here, "openapi.json");
const outFile = join(here, "src/schema.d.ts");

// `scripts/py` is a thin wrapper that runs the venv's Python natively even when the
// Node that spawned it is running under Rosetta; see the comments in that script.
const wrapper = join(apiDir, "scripts/py");
const python = existsSync(wrapper) ? wrapper : (process.env.PYTHON ?? "python3");

console.log("· dumping OpenAPI from FastAPI");
execFileSync(python, [join(apiDir, "dump_openapi.py"), schemaJson], {
  cwd: apiDir,
  stdio: "inherit",
  // The app is imported to read its schema; it must not try to reach a real database.
  env: { ...process.env, ENV: "test", DATABASE_URL: "sqlite+pysqlite:///:memory:" },
});

console.log("· generating TypeScript");
// Used as a library rather than a CLI so we do not have to guess where npm hoisted the
// binary in a workspace install.
const ast = await openapiTS(pathToFileURL(schemaJson));
writeFileSync(
  outFile,
  "/* Generated by `npm run gen:api`. Do not edit. */\n" + astToString(ast),
);

console.log("✓ packages/api-types up to date");
